package platform

import (
	"strings"
	"testing"
)

func TestGenerateAdafruitJavaScriptRequiresInput(t *testing.T) {
	_, err := GenerateAdafruitJavaScript(nil)
	if err == nil {
		t.Fatal("expected error when conversion input is nil")
	}
}

func TestGenerateAdafruitJavaScriptRendersNotes(t *testing.T) {
	input := &ConversionInput{Melody: &MelodyData{Notes: []MelodyNote{{Pitch: "C", Duration: 1}}}}
	program, err := GenerateAdafruitJavaScript(input)
	if err != nil {
		t.Fatalf("expected JavaScript output to be generated: %v", err)
	}
	if !strings.Contains(program, "// Generated by music-basicifier") {
		t.Fatalf("expected JavaScript output header, got %q", program)
	}
	if !strings.Contains(program, "input.buttonA.onEvent") {
		t.Fatalf("expected button event wrapper, got %q", program)
	}
	if !strings.Contains(program, "music.playTone(262, music.beat(BeatFraction.Quarter))") {
		t.Fatalf("expected MakeCode playTone call, got %q", program)
	}
}

func TestGenerateAdafruitJavaScriptRejectsInvalidNotes(t *testing.T) {
	_, err := GenerateAdafruitJavaScript(&ConversionInput{Melody: &MelodyData{Notes: []MelodyNote{{Pitch: "", Duration: 1}}}})
	if err == nil {
		t.Fatal("expected empty pitch to fail")
	}

	_, err = GenerateAdafruitJavaScript(&ConversionInput{Melody: &MelodyData{Notes: []MelodyNote{{Pitch: "C", Duration: 0}}}})
	if err == nil {
		t.Fatal("expected invalid duration to fail")
	}

	_, err = GenerateAdafruitJavaScript(&ConversionInput{Melody: &MelodyData{Notes: []MelodyNote{{Pitch: "H", Duration: 1}}}})
	if err == nil {
		t.Fatal("expected unsupported pitch to fail")
	}
}
